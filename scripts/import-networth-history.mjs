// Parses a "Monthly Net worth.csv" export from the family budget spreadsheet
// and emits SQL that upserts each row into `networth_history`.
//
// Usage (from repo root, in an interactive terminal):
//   node scripts/import-networth-history.mjs "path/to/Monthly Net worth.csv" \
//     > supabase/data/networth_history_import.sql
//
// The generated SQL:
//   - infers your household_id from the current authenticated user, so it works
//     without hard-coding an id — paste it into Supabase SQL Editor while signed
//     into a session that belongs to your household.
//   - upserts by (household_id, month), so re-running is safe.
//   - only writes rows for months you don't already have per-account snapshots
//     for; per-account data always wins in the UI, so overlap is harmless
//     but this keeps the fallback table clean.
//
// CSV columns used (the rest are ignored):
//   Date            e.g. "1-Dec-25"
//   NW w/out Invest banking + savings, combined (goes into bank_cents)
//   Stocks          stocks_cents
//   Debt Incurred   debt_cents
import { readFileSync } from "node:fs";
import { argv } from "node:process";

const csvPath = argv[2];
if (!csvPath) {
  console.error("Usage: node scripts/import-networth-history.mjs <path-to-csv>");
  process.exit(1);
}

const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };

// Excel-style CSV: quoted fields may contain commas ("$169,579"). Parse by
// walking the line character by character rather than a naive split(",").
function splitCsvLine(line) {
  const out = [];
  let cur = "";
  let inQuote = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuote && line[i + 1] === '"') { cur += '"'; i++; }
      else inQuote = !inQuote;
    } else if (ch === "," && !inQuote) {
      out.push(cur);
      cur = "";
    } else {
      cur += ch;
    }
  }
  out.push(cur);
  return out;
}

// "$169,579" / "-$289" / "" → cents integer (or null if blank / unparseable).
function toCents(s) {
  if (!s) return null;
  const cleaned = s.replace(/["$,\s]/g, "");
  if (cleaned === "" || cleaned === "-") return null;
  const n = Number(cleaned);
  if (!Number.isFinite(n)) return null;
  return Math.round(n * 100);
}

// "1-Dec-25" → "2025-12-01". Two-digit years assumed 20xx (spreadsheet history
// only goes back to ~2018; if you ever import 1900s data update the pivot).
function toIsoMonth(dateStr) {
  const m = /^(\d{1,2})-([A-Za-z]{3})-(\d{2,4})$/.exec(dateStr.trim());
  if (!m) return null;
  const mon = MONTHS[m[2]];
  if (!mon) return null;
  let year = Number(m[3]);
  if (year < 100) year += 2000;
  return `${year}-${String(mon).padStart(2, "0")}-01`;
}

const raw = readFileSync(csvPath, "utf8");
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0);
const header = splitCsvLine(lines[0]);

// Locate columns by header name so the script survives spreadsheet column
// reorders (only these four need to be present).
const colIdx = (name) => header.findIndex((h) => h.trim().toLowerCase() === name.toLowerCase());
const iDate = colIdx("Date");
const iBank = colIdx("NW w/out Invest");
const iStocks = colIdx("Stocks");
const iDebt = colIdx("Debt Incurred");
if (iDate < 0 || iBank < 0 || iStocks < 0 || iDebt < 0) {
  console.error("Missing expected columns. Need: Date, NW w/out Invest, Stocks, Debt Incurred");
  process.exit(1);
}

const rows = [];
for (let i = 1; i < lines.length; i++) {
  const cells = splitCsvLine(lines[i]);
  const month = toIsoMonth(cells[iDate] ?? "");
  if (!month) continue;
  const bank = toCents(cells[iBank]) ?? 0;
  const stocks = toCents(cells[iStocks]) ?? 0;
  const debt = toCents(cells[iDebt]) ?? 0;
  rows.push({ month, bank, stocks, debt });
}

// Newest-first in the CSV; sort oldest-first for a readable SQL diff.
rows.sort((a, b) => a.month.localeCompare(b.month));

const values = rows
  .map((r) => `    ('${r.month}'::date, ${r.bank}, ${r.stocks}, ${r.debt})`)
  .join(",\n");

const sql = `-- Historical net worth import — generated by scripts/import-networth-history.mjs
-- Source: ${csvPath.replace(/\\/g, "/")}
-- Rows: ${rows.length}  (${rows[0]?.month ?? "-"} → ${rows[rows.length - 1]?.month ?? "-"})
--
-- Run this in the Supabase SQL Editor while signed in as a user that belongs
-- to the household you want to load history into. The DO block infers the
-- household_id from your profile, so no ids are hard-coded.

do $$
declare
  _hh uuid;
begin
  select household_id into _hh
    from profiles
    where user_id = auth.uid()
    limit 1;
  if _hh is null then
    raise exception 'No household found for the current user (auth.uid()=%). Sign in first.', auth.uid();
  end if;

  insert into networth_history (household_id, month, savings_cents, bank_cents, stocks_cents, debt_cents)
  select _hh, v.month, 0, v.bank, v.stocks, v.debt
  from (values
${values}
  ) as v(month, bank, stocks, debt)
  on conflict (household_id, month) do update set
    bank_cents   = excluded.bank_cents,
    stocks_cents = excluded.stocks_cents,
    debt_cents   = excluded.debt_cents,
    updated_at   = now();
end $$;
`;

process.stdout.write(sql);
